# frozen_string_literal: true

# Writes the Prelude's instances for larger tuples (between the markers in
# prelude/Prelude.hs): base has Eq, Ord, Show, Read and Bounded up to
# 15-tuples, and Semigroup and Monoid up to 5-tuples. The smaller ones are
# written by hand in their classes' sections.
#
#   ruby tools/gen_tuples.rb
PRELUDE = File.expand_path('../prelude/Prelude.hs', __dir__)
BEGIN_MARK = '-- ---- larger tuples (generated by tools/gen_tuples.rb; do not edit) ----'
END_MARK = '-- ---- end of larger tuples ----'

def vars(prefix, n)
  (1..n).map { |i| "#{prefix}#{i}" }
end

def tuple(xs)
  "(#{xs.join(', ')})"
end

def context(cls, n)
  "(#{vars('a', n).map { |v| "#{cls} #{v}" }.join(', ')})"
end

def instance(cls, n, from)
  return [] if n < from

  head = "instance #{context(cls, n)} => #{cls} #{tuple(vars('a', n))} where"
  body = yield(vars('a', n), vars('b', n))
  [head] + body.map { |l| "  #{l}" } + ['']
end

lines = [BEGIN_MARK, '']
(3..15).each do |n|
  lines += instance('Eq', n, 5) { |a, b| ["#{tuple(a)} == #{tuple(b)} = #{a.zip(b).map { |x, y| "#{x} == #{y}" }.join(' && ')}"] }
  lines += instance('Ord', n, 5) do |a, b|
    cmps = a.zip(b).map { |x, y| "compare #{x} #{y}" }
    expr = cmps.reverse.reduce { |acc, c| "rhci_thenCmp (#{c}) (#{acc})" }
    ["compare #{tuple(a)} #{tuple(b)} =", "  #{expr}"]
  end
  lines += instance('Show', n, 6) { |a, _| ["showsPrec _ #{tuple(a)} s = show_tuple [#{a.map { |x| "shows #{x}" }.join(', ')}] s"] }
  lines += instance('Read', n, 6) do |a, _|
    steps = a.each_with_index.map { |x, i| i.zero? ? "readPrec >>= \\#{x} ->" : "rhci_readComma >> readPrec >>= \\#{x} ->" }
    ["readPrec = rhci_wrapTup (#{steps.join(' ')} return #{tuple(a)})",
     'readListPrec = readListPrecDefault', 'readList = readListDefault']
  end
  lines += instance('Bounded', n, 3) do |a, _|
    ["minBound = #{tuple(a.map { 'minBound' })}", "maxBound = #{tuple(a.map { 'maxBound' })}"]
  end
  next if n > 5

  lines += instance('Semigroup', n, 3) { |a, b| ["#{tuple(a)} <> #{tuple(b)} = #{tuple(a.zip(b).map { |x, y| "#{x} <> #{y}" })}"] }
  lines += instance('Monoid', n, 3) { |a, _| ["mempty = #{tuple(a.map { 'mempty' })}"] }
end
lines << END_MARK

text = File.read(PRELUDE)
section = lines.join("\n")
text = if text.include?(BEGIN_MARK)
         text.sub(/#{Regexp.escape(BEGIN_MARK)}.*#{Regexp.escape(END_MARK)}/m) { section }
       else
         "#{text.chomp}\n\n#{section}\n"
       end
File.write(PRELUDE, text)
