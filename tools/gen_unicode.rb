# frozen_string_literal: true

# Generates lib/rhci/unicode.rb from oracle/unicode/tables.txt, which is
# GHC's own view of Unicode (oracle/unicode/Tables.hs, run in the oracle
# container):
#
#   cd oracle/unicode && podman run --rm -v $PWD:/w:Z -w /w docker.io/library/haskell:9.6 \
#     sh -c 'ghc -O -outputdir /tmp -o /tmp/t Tables.hs >/dev/null && /tmp/t' > tables.txt
#   ruby tools/gen_unicode.rb
#
# The tables are compact strings, decoded on first use (see Rhci::Unicode).

ROOT = File.expand_path('..', __dir__)
lines = File.readlines(File.join(ROOT, 'oracle', 'unicode', 'tables.txt'), chomp: true)

# Category runs: a letter for the category (A + fromEnum), then the run's
# length in base 36.
cats = lines.select { |l| l.start_with?('C ') }.map { |l| l.split[1..].map(&:to_i) }
cat_text = +''
cats.each_with_index do |(start, cat), i|
  stop = i + 1 < cats.length ? cats[i + 1][0] : 0x110000
  cat_text << (65 + cat).chr << (stop - start).to_s(36)
end

def numbers(rows)
  rows.flatten.map { |n| n.to_s(36) }.join(',')
end

def rows(lines, tag)
  lines.select { |l| l.start_with?("#{tag} ") }.map { |l| l.split[1..].map(&:to_i) }
end

def pieces(text)
  out = []
  i = 0
  while i < text.length
    out << text[i, 16_000].inspect
    i += 16_000
  end
  "[\n      #{out.join(",\n      ")}\n    ].freeze"
end

tables = {
  'CATEGORY_RUNS' => cat_text,
  'UPPER_MAP' => numbers(rows(lines, 'U')),
  'LOWER_MAP' => numbers(rows(lines, 'L')),
  'TITLE_MAP' => numbers(rows(lines, 'T')),
  'UPPERCASE_RANGES' => numbers(rows(lines, 'P')),
  'LOWERCASE_RANGES' => numbers(rows(lines, 'Q'))
}

src = +<<~HEAD
  # frozen_string_literal: true

  # GENERATED by tools/gen_unicode.rb from GHC's Unicode tables
  # (oracle/unicode/tables.txt) -- do not edit.
  module Rhci
    module Unicode
HEAD
tables.each do |name, text|
  src << "    #{name} = #{pieces(text)}\n"
end
src << "  end\nend\n"
File.write(File.join(ROOT, 'lib', 'rhci', 'unicode_data.rb'), src)
puts "#{cats.length} category runs, #{src.bytesize} bytes"
