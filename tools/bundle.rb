# frozen_string_literal: true

# mruby has no `require`, so its code arrives as single files:
#   mrbgems/rhci/mrblib/rhci.rb  the library, compiled into the rhci binary
#   build/test_bundle.rb           library + harness + unit tests, for plain mruby
# Both follow lib/rhci/manifest.txt, the same order CRuby loads in.
ROOT = File.expand_path('..', __dir__)

def section(path)
  rel = path.sub("#{ROOT}/", '')
  "# ---- #{rel}\n#{File.read(path)}\n"
end

# mrbc rejects very long string literals, so long text is embedded in pieces.
def pieces(text)
  parts = []
  i = 0
  while i < text.length
    parts << text[i, 30_000].inspect
    i += 30_000
  end
  "[\n#{parts.join(",\n")}\n]"
end

lib = File.read(File.join(ROOT, 'lib', 'rhci', 'manifest.txt')).split("\n").map do |name|
  section(File.join(ROOT, 'lib', 'rhci', "#{name}.rb"))
end.join

header = "# GENERATED by tools/bundle.rb from lib/ -- do not edit.\n"
prelude = File.read(File.join(ROOT, 'prelude', 'Prelude.hs'))
# An escaped literal, not a quoted heredoc: mruby still processes \\ and \'
# inside <<'X' heredocs, which would alter the Haskell source.
lib += "# ---- prelude/Prelude.hs\nRhci::PRELUDE_SOURCE = #{pieces(prelude)}.join.freeze\n"
require_relative '../lib/rhci/base_names'
lib += "# ---- prelude/Data/...\nRhci::LIBRARY_SOURCES = {\n"
Rhci::LIBRARY_MODULES.each do |m|
  src = File.read(File.join(ROOT, 'prelude', *m.split('.')) + '.hs')
  lib += "  #{m.inspect} => #{pieces(src)}.join.freeze,\n"
end
lib += "}.freeze\n"

# The compiled Prelude (tools/snapshot.rb), regenerated on every bundle so it
# cannot go stale. The binary embeds it with the core chosen from the
# corpus; the test bundle with every entry pending, so the tests also check
# that whatever is looked up gets loaded. Each part (header, chunk of
# records) is one element, a String or an Array of pieces.
Dir.mkdir(File.join(ROOT, 'build')) unless Dir.exist?(File.join(ROOT, 'build'))
snap_path = File.join(ROOT, 'build', 'prelude.snapshot')
on_demand_path = File.join(ROOT, 'build', 'prelude-ondemand.snapshot')
system(RbConfig.ruby, File.join(ROOT, 'tools', 'snapshot.rb'), snap_path, on_demand_path, exception: true)
def snapshot_parts(path)
  parts = File.read(path).split("\f").map { |p| p.length <= 30_000 ? p.inspect : pieces(p) }
  "# ---- #{path.sub("#{ROOT}/", '')}\nRhci::PRELUDE_SNAPSHOT_PARTS = [\n#{parts.join(",\n")}\n].freeze\n"
end
File.write(File.join(ROOT, 'mrbgems', 'rhci', 'mrblib', 'rhci.rb'), header + lib + snapshot_parts(snap_path))
snapshot = snapshot_parts(on_demand_path)

tests = [File.join(ROOT, 'test', 'harness.rb'), File.join(ROOT, 'test', 'oracle.rb'),
         File.join(ROOT, 'test', 'core_sexp.rb')] +
        Dir[File.join(ROOT, 'test', 'unit', '*_test.rb')].sort
File.write(File.join(ROOT, 'build', 'test_bundle.rb'),
           header + "RHCI_ROOT = #{ROOT.inspect}\n" + lib + snapshot + tests.map { |t| section(t) }.join +
           "exit(RT.run ? 0 : 1)\n")
