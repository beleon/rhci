# frozen_string_literal: true

# Regenerates lib/rhci/base_names.rb from GHCi's own `:browse` of the
# modules rhci puts in scope by default. CRuby-only tool (needs podman).
ROOT = File.expand_path('..', __dir__)
MODULES = %w[Prelude Data.List Data.Maybe Data.Char Data.Tuple Data.Function Data.Ord Data.Either
             Control.Monad].freeze

# Import everything first, so names print unqualified.
script = MODULES.map { |m| "import #{m}\n" }.join +
         MODULES.map { |m| ":browse #{m}\n:! echo '@@MODULE-END@@'\n" }.join
out = IO.popen(['podman', 'run', '--rm', '-i', 'docker.io/library/haskell:9.6', 'sh', '-c',
                'ghci -ignore-dot-ghci -v0 2>&1'], 'r+') do |io|
  io.write(script)
  io.close_write
  io.read
end
chunks = out.split("@@MODULE-END@@\n")
raise "expected #{MODULES.length} modules, got #{chunks.length}" if chunks.length < MODULES.length

# M.x or M.+ (a module prefix), as opposed to an operator such as `.`.
def qualified?(name)
  i = name.index('.')
  !i.nil? && i.positive? && name[0] >= 'A' && name[0] <= 'Z'
end

values = {}
types = {}
MODULES.each_with_index do |mod, i|
  # Join `data` declarations continued on indented `=`/`|` lines.
  lines = []
  chunks[i].split("\n").each do |line|
    if (line.start_with?('  = ') || line.start_with?('  | ')) && !lines.empty?
      lines[-1] = "#{lines[-1]} #{line.strip}"
    else
      lines << line
    end
  end
  lines.each do |line|
    next if line.include?('{-#')

    if (m = line.match(/\A\s*(\(.+?\)|[a-z_][A-Za-z0-9_']*) ::/))
      name = m[1]
      name = name[1..-2] if name.start_with?('(')
      values[name] ||= mod unless qualified?(name)
    elsif (m = line.match(/\Atype ([A-Z][A-Za-z0-9_']*) ::/))
      types[m[1]] ||= mod
    elsif (m = line.match(/\A(?:data|newtype) [^=]*= (.*)\z/))
      m[1].split(' | ').each do |alt|
        con = alt.strip.split(/[ {]/).first
        con = con[1..-2] if con.start_with?('(')
        values[con] ||= mod unless con.include?('.') || con.include?('#')
      end
    end
  end
end

def ruby_hash(h)
  h.keys.sort.map { |k| "    #{k.inspect} => #{h[k].inspect}," }.join("\n")
end

File.write(File.join(ROOT, 'lib', 'rhci', 'base_names.rb'), <<~RUBY)
  # frozen_string_literal: true

  # GENERATED by tools/gen_base_names.rb from GHCi's `:browse` -- do not edit.
  # Every value and type name GHCi has in scope from the modules rhci puts
  # in scope by default, with the module that exports it. A name listed here
  # that rhci does not define yet is reported as "not implemented yet", never
  # as "not in scope".
  module Rhci
    BASE_VALUES = {
  #{ruby_hash(values)}
    }.freeze

    BASE_TYPES = {
  #{ruby_hash(types)}
    }.freeze
  end
RUBY
puts "#{values.length} values, #{types.length} types"
